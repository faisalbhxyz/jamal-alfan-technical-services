export function getPost(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find((post) => post.slug === slug);
}

export function getPostsByService(slug: string): BlogPost[] {
  return BLOG_POSTS.filter((post) => post.serviceSlug === slug);
}

export function getRelatedPosts(slug: string): BlogPost[] {
  const current = getPost(slug);
  if (!current) {
    return [];
  }
  const rest = BLOG_POSTS.filter((post) => post.slug !== slug);
  const sameTrade = rest.filter((post) => post.serviceSlug === current.serviceSlug);
  const otherTrades = rest.filter((post) => post.serviceSlug !== current.serviceSlug);
  return [...sameTrade, ...otherTrades].slice(0, 3);
}

export function formatBlogDate(iso: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-AE" : "en-GB", {
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(new Date(`${iso}T12:00:00Z`));
}
